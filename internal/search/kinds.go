package search

import (
	"bytes"
	"path"
	"strings"
)

// File categories for the is:test, is:generated and is:vendored filters.
// Ranking uses the same classification, so a file the filters call a
// test is also the file ranking demotes as one.

var (
	testDirs = []string{"/test/", "/tests/", "/testing/", "/testdata/", "/__tests__/", "/javatests/", "/androidtest/", "/unittests/", "/test_data/"}
	// test file name suffixes, compared case-sensitively
	testSuffixes = []string{"_test.go", "_test.py", "_test.cc", "_test.cpp", "_test.c", "_unittest.cc", "_unittest.cpp",
		"_browsertest.cc", "_test.rb", "_spec.rb", "_test.rs", "_test.dart", "_tests.cc",
		"Test.java", "Tests.java", "Test.kt", "Tests.kt", "Test.scala", "Spec.scala", "Tests.swift", "Test.swift", "Tests.cs", "Test.cs", "Test.php"}
	// test file name infixes, compared case-insensitively: foo.test.ts, foo.spec.js
	testInfixes = []string{".test.", ".spec.", "_test_", ".tests."}

	vendorDirs = []string{"/third_party/", "/third-party/", "/thirdparty/", "/external/", "/vendor/", "/node_modules/",
		"/prebuilts/", "/prebuilt/", "/bower_components/", "/site-packages/", "/pods/", "/deps/"}

	generatedSuffixes = []string{".pb.go", ".pb.h", ".pb.cc", ".pb.c", "_pb2.py", "_pb2_grpc.py", "_pb.js", "_pb.d.ts",
		".pb.swift", ".g.dart", ".freezed.dart", ".gen.go", "_gen.go", "_generated.go", "_string.go", ".designer.cs", ".g.cs"}
	generatedInfixes = []string{"/generated/", "/gen/", "/autogen/", ".generated.", "_generated.", "/__generated__/"}
)

func isTestPath(p string) bool {
	lp := "/" + strings.ToLower(p)
	for _, d := range testDirs {
		if strings.Contains(lp, d) {
			return true
		}
	}
	base := path.Base(p)
	for _, s := range testSuffixes {
		if strings.HasSuffix(base, s) {
			return true
		}
	}
	lb := strings.ToLower(base)
	if strings.HasPrefix(lb, "test_") && strings.HasSuffix(lb, ".py") {
		return true
	}
	for _, s := range testInfixes {
		if strings.Contains(lb, s) {
			return true
		}
	}
	return false
}

func isVendoredPath(p string) bool {
	lp := "/" + strings.ToLower(p)
	for _, d := range vendorDirs {
		if strings.Contains(lp, d) {
			return true
		}
	}
	return false
}

func isGeneratedPath(p string) bool {
	lp := "/" + strings.ToLower(p)
	for _, s := range generatedSuffixes {
		if strings.HasSuffix(lp, strings.ToLower(s)) {
			return true
		}
	}
	for _, s := range generatedInfixes {
		if strings.Contains(lp, s) {
			return true
		}
	}
	return false
}

// generatedHeadLen is how much of a file is checked for a generated-code marker.
const generatedHeadLen = 1024

// isGeneratedContent reports whether the start of a file says it was
// generated, as in Go's "Code generated ... DO NOT EDIT." convention or
// an "@generated" marker.
func isGeneratedContent(data []byte) bool {
	head := data[:min(len(data), generatedHeadLen)]
	if bytes.Contains(head, []byte("@generated")) || bytes.Contains(head, []byte("DO NOT EDIT")) {
		return true
	}
	lower := bytes.ToLower(head)
	for _, m := range []string{"code generated by", "autogenerated", "auto-generated", "automatically generated", "this file was generated", "this file is generated"} {
		if bytes.Contains(lower, []byte(m)) {
			return true
		}
	}
	return false
}

// classifyFile sets the category flags of a match. data may be nil if
// the file's contents were not read.
func classifyFile(f *FileMatch, data []byte) {
	f.test = isTestPath(f.Path)
	f.vendored = isVendoredPath(f.Path)
	f.generated = isGeneratedPath(f.Path) || data != nil && isGeneratedContent(data)
}
