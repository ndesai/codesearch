package search

import "testing"

func TestCategories(t *testing.T) {
	for _, tt := range []struct {
		path            string
		test, gen, vend bool
	}{
		{"pkg/reader_test.go", true, false, false},
		{"src/test/java/a/FooTest.java", true, false, false},
		{"src/Contest.java", false, false, false},
		{"web/app.spec.ts", true, false, false},
		{"tests/test_parse.py", true, false, false},
		{"chrome/browser/foo_browsertest.cc", true, false, false},
		{"api/v1/service.pb.go", false, true, false},
		{"proto/service_pb2.py", false, true, false},
		{"out/gen/foo.h", false, true, false},
		{"third_party/skia/src/a.cpp", false, false, true},
		{"node_modules/react/index.js", false, false, true},
		{"external/zlib/test/minigzip.c", true, false, true},
		{"frameworks/base/core/java/android/app/Activity.java", false, false, false},
	} {
		if g := isTestPath(tt.path); g != tt.test {
			t.Errorf("isTestPath(%s) = %v", tt.path, g)
		}
		if g := isGeneratedPath(tt.path); g != tt.gen {
			t.Errorf("isGeneratedPath(%s) = %v", tt.path, g)
		}
		if g := isVendoredPath(tt.path); g != tt.vend {
			t.Errorf("isVendoredPath(%s) = %v", tt.path, g)
		}
	}
	for src, want := range map[string]bool{
		"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n":  true,
		"/* @generated by Relay */\n":                                    true,
		"# This file is automatically generated by tool.py\n":            true,
		"package x\n\n// Generate creates things.\nfunc Generate() {}\n": false,
	} {
		if g := isGeneratedContent([]byte(src)); g != want {
			t.Errorf("isGeneratedContent(%q) = %v", src, g)
		}
	}
}
